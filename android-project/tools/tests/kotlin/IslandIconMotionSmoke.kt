package io.atmos.weather.notifications

fun main() {
    fun scene(kind:String,title:String,detail:String="")=IslandIconClassifier.choose(kind,title,detail)
    check(scene("ALARM_RINGING","07:30 鬧鐘響鈴中")==IslandIconScene.ALARM)
    check(scene("SEISMIC_EEW","地震速報")==IslandIconScene.QUAKE)
    check(scene("WEATHER_WARNING","海上颱風警報")==IslandIconScene.TYPHOON)
    check(scene("WEATHER_WARNING","雷雨警報")==IslandIconScene.THUNDER)
    check(scene("WEATHER_WARNING","豪雨特報")==IslandIconScene.RAIN)
    check(scene("WEATHER_WARNING","高溫警示")==IslandIconScene.HOT)
    check(scene("WEATHER_WARNING","低溫警示")==IslandIconScene.COLD)
    check(scene("AMBIENT_WEATHER","紫外線偏強")==IslandIconScene.UV)
    check(scene("AMBIENT_WEATHER","AQI 42")==IslandIconScene.AIR)
    check(scene("AMBIENT_WEATHER","降雪")==IslandIconScene.SNOW)
    check(scene("AMBIENT_WEATHER","多雲")==IslandIconScene.CLOUD)
    check(scene("AMBIENT_WEATHER","晴朗")==IslandIconScene.SUN)
    check(scene("TIMER_RUNNING","10 分倒數")==IslandIconScene.TIMER)
    check(scene("TASK_REMINDER","記得領包裹")==IslandIconScene.NOTE)
    check(scene("TASK_REMINDER","下午會議")==IslandIconScene.CALENDAR)
    check(scene("VERIFIED_MINUTE_RAIN","預計 5 分鐘內下雨")==IslandIconScene.RAIN)
    val t=100_000L
    val first=IslandIconMotionPolicy.next(null,"alarm-on",t,true,false)
    check(first.frame==1)
    check(IslandIconMotionPolicy.next(first,"alarm-on",t+200,true,false).frame==1)
    val next=IslandIconMotionPolicy.next(first,"alarm-on",t+12_001,true,false)
    check(next.frame==0)
    check(IslandIconMotionPolicy.next(next,"timer:started",t+12_002,true,false).frame==1)
    check(IslandIconMotionPolicy.next(first,"alarm-on:tick",t+200,true,false).frame==1)
    check(IslandIconMotionPolicy.next(first,"alarm-on:later",t+18_000,true,false).frame==0)
    check(IslandIconMotionPolicy.next(first,"alarm-on",t+30_000,false,false).frame==0)
    check(IslandIconMotionPolicy.next(first,"alarm-on",t+30_000,true,true).frame==0)
    println("IslandIconMotionSmoke: 25 checks passed")
}
